def getMyPosition(prcSoFar):
    prices = np.asarray(prcSoFar, dtype=float)
    n_inst, n_days = prices.shape
    if n_days < WARMUP or n_days < 3:
        return np.zeros(n_inst, dtype=int)

    returns = np.diff(np.log(np.maximum(prices, 1e-12)), axis=1)
    latest = returns[:, -1]
    previous = returns[:, -(SCALE_WINDOW + 1):-1]
    if previous.shape[1] < 3:
        previous = returns[:, :-1]

    target_dollars = np.zeros(n_inst, dtype=float)

    for target, edges in NETWORK.items():
        if target >= n_inst:
            continue
        current_forecast = 0.0
        historical_forecast = np.zeros(previous.shape[1], dtype=float)
        for source, weight in edges:
            if source >= n_inst:
                continue
            current_forecast += weight * latest[source]
            historical_forecast += weight * previous[source]
        scale = max(float(historical_forecast.std()), 1e-6)
        confidence = NETWORK_GAIN * current_forecast / scale
        target_dollars[target] = LEG * float(np.clip(confidence, -1.0, 1.0))

    # Explicit factor alpha, not a disguised hedge: broad same-day participation
    # tends to mean-revert in ALGO on the following day in each development block.
    breadth_now = float(np.mean(latest[1:] > 0.0) - 0.5)
    breadth_history = np.mean(previous[1:] > 0.0, axis=0) - 0.5
    breadth_scale = max(float(breadth_history.std()), 1e-6)
    breadth_forecast = -BREADTH_GAIN * breadth_now / breadth_scale
    target_dollars[0] = ALGO_LIMIT * float(np.clip(breadth_forecast, -1.0, 1.0))

    current_prices = prices[:, -1]
    dollar_limits = np.full(n_inst, LEG, dtype=float)
    dollar_limits[0] = ALGO_LIMIT
    share_limits = (dollar_limits / np.maximum(current_prices, 1e-12)).astype(int)
    shares = (target_dollars / np.maximum(current_prices, 1e-12)).astype(int)
    return np.clip(shares, -share_limits, share_limits).astype(int)
